#!/usr/bin/env python3
"""Generate source tables from pinned 9W9 UI metadata and original PCM WAVs.
9W9 by A Thousand Details - https://github.com/athousanddetails/schwung-9W9
Modified for Orbit; GPL-3.0 with additional terms in the upstream NOTICE.
"""
from pathlib import Path
import ast,json,re,struct,wave
root=Path(__file__).resolve().parents[1];vendor=root/'Source/Synth/ThirdParty/9W9'
source=(vendor/'9w9_params.h').read_text()
def strings(name):
    start=source.index('static const char '+name+'[]');end=source.index(';',start)
    return json.loads(''.join(ast.literal_eval(s) for s in re.findall(r'"(?:\\.|[^"\\])*"',source[start:end])))
params=[p for p in strings('w9_chain_params_json') if p['key']!='note_map'];hierarchy=strings('w9_ui_hierarchy_json')['levels']
params.append(dict(key='orbit_step_accent',name='Step Accent',type='int',min=0,max=100))
params.append(dict(key='orbit_note_map',name='Note Map',type='enum',options=['General MIDI','9W9 Pads']))
index={p['key']:i for i,p in enumerate(params)}
pages=[]
for key in ['bd','sd','lt','mt','ht','rim','clap','ohh','chh','ride','crash','master','reverb','delay']:
    if key in hierarchy:
        h=hierarchy[key];pages.append((h['name'],h['knobs']))
    else:
        prefix='rev_' if key=='reverb' else 'dly_' if key=='delay' else None
        keys=[p['key'] for p in params if prefix and p['key'].startswith(prefix)] if prefix else ['master_dist','master_drive','master_comp','volume','accent','vel_depth','orbit_step_accent','orbit_note_map']
        pages.append((key.title(),keys))
# The upstream master page can be named main; use a fixed complete master view.
pages[11]=('Master',['master_dist','master_drive','master_comp','volume','accent','vel_depth','orbit_step_accent','orbit_note_map'])
def q(s):return json.dumps(s,ensure_ascii=True)
text='// Generated by Tools/generate-ninekit-data.py. GPL-3.0 + NOTICE; modified for Orbit.\n// 9W9 by A Thousand Details - https://github.com/athousanddetails/schwung-9W9\n#pragma once\n#include <array>\n#include <vector>\nnamespace orbit::synth::nine {\nstruct Spec {const char* id;const char* name;int maximum;const char* choices;};\ninline constexpr std::array<Spec,'+str(len(params))+'> specs{{\n'
for p in params:text+='{'+q(p['key'])+','+q(p['name'])+','+str(len(p['options'])-1 if p['type']=='enum' else p.get('max',127))+','+q('|'.join(p.get('options',[])))+'},\n'
text+='}};\nstruct Page {const char* name;std::vector<int> parameters;};\ninline const std::array<Page,14> pages{{\n'
for name,keys in pages:text+='{'+q(name)+',{'+','.join(str(index[k]) for k in keys if k in index)+'}},\n'
text+='}};\ninline constexpr std::array<int,11> gmNotes{36,38,41,47,50,37,39,46,42,51,49};\ninline constexpr std::array<int,11> padNotes{36,37,38,39,40,41,42,44,43,46,45};\n}\n'
(root/'Source/Synth/NineKitMetadata.h').write_text(text)
text='/* Generated PCM source assets from the pinned upstream GPL repository.\n * 9W9 by A Thousand Details - https://github.com/athousanddetails/schwung-9W9\n * Modified for Orbit: decoded into float source tables; see NOTICE and UPSTREAM.md. */\n#ifndef ORBIT_NINE_SAMPLES_H\n#define ORBIT_NINE_SAMPLES_H\n'
for name in ['hh','ride','crash']:
    with wave.open(str(vendor/'samples'/f'{name}.wav')) as w:
        assert w.getnchannels()==1 and w.getframerate()==44100
        raw=w.readframes(w.getnframes());width=w.getsampwidth()
        values=[int.from_bytes(raw[i:i+width],'little',signed=True)/(2**(width*8-1)) for i in range(0,len(raw),width)]
    text+=f'static const float orbit_nine_{name}[{len(values)}]={{\n'
    for start in range(0,len(values),12):text+=','.join(f'{x:.9e}f' for x in values[start:start+12])+',\n'
    text+='};\n'
text+='#endif\n';(root/'Source/Synth/NineKitSamples.h').write_text(text)
print(f'Generated {len(params)} parameters, {len(pages)} pages and three sample tables.')
